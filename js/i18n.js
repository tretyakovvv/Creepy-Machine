  function getNode(lang, keys) {
    let node = translations[lang];
    for (const k of keys) node = node?.[k];
    if (node !== undefined) return node;
    node = translations.en;
    for (const k of keys) node = node?.[k];
    return node;
  }

  function t(key, vars = {}) {
    const lang = window.CMStore.getLang();
    const keys = key.split(".");
    let node = getNode(lang, keys);
    if (node === undefined && lang !== "en") node = getNode("en", keys);
    if (typeof node !== "string") return key;
    return node.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? "");
  }

  function getLegal(page) {
    const lang = window.CMStore.getLang();
    return legal[page]?.[lang] || legal[page]?.en;
  }

  window.CMI18n = { t, getLegal, translations, legal };
